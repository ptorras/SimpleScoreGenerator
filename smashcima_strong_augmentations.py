"""Stronger, higher-variability drop-in replacements for two pieces of the
default Smashcima handwritten pipeline:

- `WavyStafflinesSynthesizer`: like `NaiveStafflinesSynthesizer`, but each
  staffline gets its own randomized stroke width (varying along its length,
  not just a fixed rectangle) and a gentle non-straight wobble, so lines
  don't look ruler-drawn.
- `StrongHandwrittenPostprocessor`: like `BaseHandwrittenPostprocessor`, but
  adds Kanungo-style foreground/background noise, foreground
  dilation/erosion, extra background noise and stray background text, an
  extra full-page affine jitter, and a small independent ink-layer jitter.
  The extra ink/paper filters specifically take advantage of the fact that
  ink, stafflines and paper are still separate layers at this stage of the
  pipeline - something a flattened image could not exploit. Every filter
  that warps geometry (rotation, the affine jitter, the ink-layer jitter)
  also keeps a caller-provided list of glyph bounding boxes in sync, so
  they stay correct after augmentation; its own `Folding` (paper-fold) is
  disabled since that particular warp can't be tracked precisely enough.

Both classes are meant to be wired into a `MppModel`-style orchestration
model in place of the stock Smashcima services (see
`generate_smashcima_dataset_strong.py`).
"""

import random
import sys
from typing import List, Tuple

import cv2
import numpy as np

import smashcima as sc
from smashcima.exporting.image.ImageLayer import ImageLayer
from smashcima.exporting.image.LayerSet import LayerSet
from smashcima.exporting.postprocessing.BaseHandwrittenPostprocessor import (
    BaseHandwrittenPostprocessor,
)
from smashcima.exporting.postprocessing.Filter import Filter
from smashcima.exporting.postprocessing.FilterStack import FilterStack
from smashcima.geometry.units import mm_to_px
from smashcima.synthesis.page.NaiveStafflinesSynthesizer import (
    NaiveStafflinesSynthesizer,
)


# =============================================================================
# Stafflines: variable stroke width + gentle waviness
# =============================================================================


class WavyStafflinesSynthesizer(NaiveStafflinesSynthesizer):
    """Draws stafflines as rasterized, hand-drawn-looking strokes instead of
    perfectly straight, uniform-width rectangles.

    Each staffline independently gets:
    - a random overall stroke width (so lines within a staff, and staves
      across a page, are not all identically thick), and
    - a small amount of low-frequency waviness and thickness wobble along
      its length, generated by interpolating a handful of random control
      points (so the line "breathes" like a real pen stroke would, without
      becoming jagged).
    """

    def __init__(
        self,
        rng: random.Random,
        thickness_range: Tuple[float, float] = (0.6, 1.6),
        waviness_range_mm: Tuple[float, float] = (0.0, 0.20),
        thickness_wobble_fraction: float = 0.5,
    ) -> None:
        super().__init__()
        self.rng = rng
        self.thickness_range = thickness_range
        self.waviness_range_mm = waviness_range_mm
        self.thickness_wobble_fraction = thickness_wobble_fraction

    def create_staff_glyph(
        self,
        staff_space: "sc.AffineSpace",
        width: float,
    ) -> "sc.ComposedGlyph":
        sub_glyphs: List["sc.Glyph"] = []

        for line_offset in range(-2, 3):
            base_y = line_offset * self.staff_space_unit
            sub_glyphs.append(self._make_wavy_line_glyph(width, base_y))

        composed_glyph = sc.ComposedGlyph.build(
            label=sc.SmashcimaLabels.staff.value,
            sub_glyphs=sub_glyphs,
        )
        composed_glyph.space.parent_space = staff_space

        return composed_glyph

    def _make_wavy_line_glyph(self, width: float, base_y: float) -> "sc.Glyph":
        dpi = 300
        rng = self.rng

        line_thickness_mm = self.line_thickness * rng.uniform(*self.thickness_range)
        waviness_amp_mm = rng.uniform(*self.waviness_range_mm)
        thickness_wobble_mm = (
            line_thickness_mm * rng.uniform(0.0, self.thickness_wobble_fraction)
        )

        pixel_width = max(int(mm_to_px(width, dpi=dpi)), 1)

        # enough vertical padding to fit the thickest/most-wobbly variant
        half_extent_mm = (
            line_thickness_mm / 2 + thickness_wobble_mm / 2 + waviness_amp_mm + 0.15
        )
        pixel_half_extent = max(int(mm_to_px(half_extent_mm, dpi=dpi)), 2)
        pixel_height = pixel_half_extent * 2

        # a handful of random control points, interpolated across the width,
        # gives a smooth (not jagged) wobble in both position and thickness
        n_ctrl = max(4, pixel_width // 60 + 2)
        xs_ctrl = np.linspace(0, pixel_width - 1, n_ctrl)
        y_ctrl = [rng.gauss(0.0, waviness_amp_mm) for _ in range(n_ctrl)]
        t_ctrl = [rng.gauss(0.0, thickness_wobble_mm / 2) for _ in range(n_ctrl)]

        xs = np.arange(pixel_width)
        center_offset_mm = np.interp(xs, xs_ctrl, y_ctrl)
        thickness_delta_mm = np.interp(xs, xs_ctrl, t_ctrl)

        # mm_to_px() only accepts scalars, so convert the per-column arrays
        # by hand using the px-per-mm ratio at this DPI
        px_per_mm = mm_to_px(1.0, dpi=dpi)
        center_px = pixel_half_extent + center_offset_mm * px_per_mm
        half_thickness_px = np.clip(
            (line_thickness_mm / 2 + thickness_delta_mm) * px_per_mm,
            1.0,
            None,
        )

        top = np.clip(
            np.floor(center_px - half_thickness_px), 0, pixel_height - 1
        ).astype(int)
        bottom = np.clip(
            np.ceil(center_px + half_thickness_px), 0, pixel_height - 1
        ).astype(int)

        bitmap = np.zeros((pixel_height, pixel_width, 4), dtype=np.uint8)
        rows = np.arange(pixel_height)[:, np.newaxis]
        mask = (rows >= top[np.newaxis, :]) & (rows <= bottom[np.newaxis, :])
        bitmap[mask] = self.line_color

        line_space = sc.AffineSpace()
        sprite = sc.Sprite(
            space=line_space,
            bitmap=bitmap,
            bitmap_origin=sc.Point(0.5, 0.5),
            dpi=dpi,
        )
        sprite.transform = sc.Transform.translate(sc.Vector2(width / 2, base_y))

        # extracting the region from the actual rasterized alpha channel
        # (rather than assuming a rectangle) keeps the staffline bounding
        # box accurate despite the waviness/thickness variation
        region = sc.Glyph.build_region_from_sprites_alpha_channel(
            label=sc.SmashcimaLabels.staffLine.value,
            sprites=[sprite],
        )

        return sc.Glyph(space=line_space, region=region, sprites=[sprite])


